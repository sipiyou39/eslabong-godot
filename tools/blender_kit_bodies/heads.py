def leaf(base, tip, width, thick, up=(0, 1, 0), m=7, n=8, bulge=0.0, side=1.0, cd=(0, 0, 0), swap=False):
    """feuille plate (oreille, aile fine) entre base et tip, large dans la direction up."""
    b, t = np.asarray(base, float), np.asarray(tip, float)
    mid = (b + t) / 2 + np.asarray(cd, float)
    path = bez(b, b + (mid - b) * 1.2, t + (mid - t) * 0.6, t, m)
    rad = []
    for i in range(m):
        u = i / (m - 1)
        prof = (math.sin(min(1.0, u * 1.0 + 0.15) * math.pi * 0.5 + 0.0)) * (1 - u) ** 0.8 + 0.12 * (1 - u)
        w = width * (0.35 + 0.65 * (math.sin(u * math.pi) ** 0.6)) * (1 - u ** 3)
        a_, b_ = max(w, 1e-4), thick * (1 - 0.6 * u) + 1e-4
        rad.append((b_, a_) if swap else (a_, b_))
    rad[-1] = (0.0, 0.0)
    return tube(path, rad, n=n, cap0='ngon', up=up)


def eyes_dark(y, x, z, r=0.027, sq=1.2, rot=0.0):
    out = []
    for sx in (-1, 1):
        g = sphere(r, r * sq, r * 0.8, n=10, m=6).rz(sx * rot).t(sx * x, y, z)
        out.append(g)
    return out


def fangs(pts, length=0.04, r=0.012):
    return [spike((x, y, z), (x, y - length, z + 0.004), r=r, n=6, bulge=0.8) for (x, y, z) in pts]


