def neck_piece(h, r=0.082, col=SKIN):
    neck = rows_loft([(1.10, r * 1.03, r * 1.03, -0.005), (1.20, r, r, 0.0), (1.27, r, r, 0.0)], n=14, cap0='ngon', cap1='ngon')
