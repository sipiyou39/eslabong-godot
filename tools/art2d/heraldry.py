def shield_form(i):
    c = lambda pts, n=12, closed=True: catmull(pts, n, closed)
    if i == 0:   # heater
        return shield_pts(0.78, -0.86, 0.92, 14)
    if i == 1:   # kite allonge
        return c([(-0.62, -0.78), (0, -0.88), (0.62, -0.78), (0.64, -0.1), (0.4, 0.45), (0, 0.94), (-0.4, 0.45), (-0.64, -0.1)])
    if i == 2:   # rond
        t = np.linspace(0, 2 * PI, 80, endpoint=False)
        return np.stack([0.86 * np.cos(t), 0.86 * np.sin(t)], 1)
    if i == 3:   # ibérique (carre bas arrondi)
        return np.vstack([[(-0.74, -0.84), (0.74, -0.84)], Draw.arc_pts(0, 0.1, 0.74, 0.76, 0, 180, 30)])
    if i == 4:   # français (angles bas arrondis, pointe)
        return c([(-0.72, -0.84), (0.72, -0.84), (0.74, 0.2), (0.45, 0.6), (0, 0.92), (-0.45, 0.6), (-0.74, 0.2)], 8)
    if i == 5:   # hexagonal
        return np.array([(0.0, -0.9), (0.78, -0.45), (0.78, 0.45), (0, 0.9), (-0.78, 0.45), (-0.78, -0.45)])
    if i == 6:   # a bouches (echancrure en haut)
        pts = [(-0.74, -0.82), (-0.4, -0.88), (-0.3, -0.7), (0.3, -0.7), (0.4, -0.88), (0.74, -0.82), (0.76, 0.0), (0.5, 0.55), (0, 0.9), (-0.5, 0.55), (-0.76, 0.0)]
        return np.array(pts)
    # 7 : losange arrondi
    return c([(0, -0.92), (0.64, -0.2), (0.0, 0.92), (-0.64, -0.2)], 8)


def shield_masks(i):
    D = Draw(S, S, SS)
    D.poly(shield_form(i))
    m = D.mask()
    o = dilate(m, 4.5 * SS) - m
    return m, np.clip(o, 0, 1)


