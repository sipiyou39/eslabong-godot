def division(i):
    D = Draw(S, S, SS, norm=False)
    full = [(0, 0), (S, 0), (S, S), (0, S)]
    if i == 0:
        pass
    elif i == 1:
        D.rect(64, 0, S, S)
    elif i == 2:
        D.rect(0, 64, S, S)
    elif i == 3:
        D.poly([(0, 0), (0, S), (S, S)])
    elif i == 4:
        D.poly([(S, 0), (0, S), (S, S)])
    elif i == 5:
        D.path([(-6, 100), (64, 40), (134, 100)], 30, cap=False)
        D.poly([(-6, 85), (64, 25), (134, 85), (134, 115), (64, 55), (-6, 115)])
